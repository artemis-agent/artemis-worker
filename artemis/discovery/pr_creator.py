import pathlib

import yaml
from github import Auth, Github

from artemis.core.config import settings


async def create_company_pr(
    slug: str,
    config_data: dict,
    sample_jobs: list[dict],
    detection_details: str,
) -> str | None:
    if not settings.github_token or not settings.github_repo:
        print(f"GitHub not configured. Would create PR for {slug}")
        print(f"Config: {config_data}")
        return None

    auth = Auth.Token(settings.github_token)
    g = Github(auth=auth)
    repo = g.get_repo(settings.github_repo)

    branch_name = f"add-company/{slug}"
    default_branch = repo.default_branch
    ref = repo.get_git_ref(f"heads/{default_branch}")
    sha = ref.object.sha

    try:
        repo.create_git_ref(f"refs/heads/{branch_name}", sha)
    except Exception:
        # Branch may already exist
        pass

    # Create YAML config file
    yaml_content = yaml.dump(config_data, default_flow_style=False, sort_keys=False)
    file_path = f"configs/companies/{slug}.yaml"

    try:
        repo.create_file(
            path=file_path,
            message=f"Add company config: {config_data.get('name', slug)}",
            content=yaml_content,
            branch=branch_name,
        )
    except Exception:
        contents = repo.get_contents(file_path, ref=branch_name)
        repo.update_file(
            path=file_path,
            message=f"Update company config: {config_data.get('name', slug)}",
            content=yaml_content,
            sha=contents.sha,
            branch=branch_name,
        )

    # Build PR description
    sample_titles = "\n".join(f"- {j.get('title', 'N/A')}" for j in sample_jobs[:5])
    body = f"""## Auto-discovered company: {config_data.get('name', slug)}

**ATS Type:** `{config_data.get('ats', 'unknown')}`
**Careers URL:** {config_data.get('careers_url', 'N/A')}
**Detection:** {detection_details}
**Sample Jobs Found:** {len(sample_jobs)}

### Sample Job Titles
{sample_titles}

### Config
```yaml
{yaml_content}
```

---
_This PR was auto-generated by the Artemis Discovery Agent._
"""

    pr = repo.create_pull(
        title=f"Add company: {config_data.get('name', slug)}",
        body=body,
        head=branch_name,
        base=default_branch,
    )

    # Add labels
    try:
        pr.add_to_labels("auto-discovered", config_data.get("ats", "unknown"))
    except Exception:
        pass

    g.close()
    return pr.html_url
