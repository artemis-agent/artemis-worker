def fetch_curated() -> list[dict]:
    """Return curated list as candidate dicts compatible with probe.gather_candidates()."""
    from artemis.discovery.curated_batch2 import CURATED_BATCH_2
    from artemis.discovery.curated_batch3 import CURATED_BATCH_3

    seen: set[str] = set()
    out: list[dict] = []
    for name in CURATED_TECH_COMPANIES + CURATED_BATCH_2 + CURATED_BATCH_3:
        key = name.lower().strip()
        if key in seen:
            continue
        seen.add(key)
        out.append({"name": name, "website": "", "source": "curated"})
    return out
